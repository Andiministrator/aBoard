const STRINGS = { de: DE, en: EN };

let lang = 'en';

function setLang(l) {
  lang = l === 'de' ? 'de' : 'en';
}

/* Aktuelle UI-Sprache ('de'|'en') — u. a. für die Intl-Locale-Wahl im
   Kalender (ADR-0103: Monats-/Wochentagsnamen via Intl.DateTimeFormat). */
function getLang() {
  return lang;
}

function t(key, ...args) {
  const dict = STRINGS[lang] ?? EN;
  const val  = dict[key] ?? EN[key] ?? key;
  return typeof val === 'function' ? val(...args) : val;
}

export const I18n = { setLang, getLang, t };
